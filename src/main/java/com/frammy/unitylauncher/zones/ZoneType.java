package com.frammy.unitylauncher.zones;

public enum ZoneType {
    /**
    может создавать только правитель
    внутри при создании ничего не должно быть

    Если удаляется зона страны, полностью удаляется страна (сделать увед в чат на всякий)
    В апдейт углов зоны сделать кулдаун 2 дня (зоны страны и колоний)

    может существовать только одна

    когда создаешь страну, тебе доступны: 5 АТМ
     */
    COUNTRY,
    /**
     * "Участок" — базовая единица для всех зон.
     * Не привязан к стране/колонии, не имеет смысловой специализации —
     * просто застолблённая игроком территория (для дома и т.п.).
     * Может быть бесплатно "повышен" (UPGRADE_TYPE) до любого из обычных
     * типов (SHOP/BANK/HOSPITAL/INDUSTRIAL/PARK/CHURCH/LIBRARY/GREENHOUSE),
     * если у игрока/страны есть свободная квота (ZoneQuotaService) и площадь
     * участка укладывается в лимиты целевого типа. COUNTRY/COLONY через
     * повышение недостижимы — они создаются только правителем отдельно.
     */
    PLOT,
    /**
     * может создавать только правитель
     *     колония может находится в любом мире
     *     внутри при создании ничего не может быть
     *     может быть несколко (можно увеличивать апгрейдом) (добавить)*/
    COLONY,
    /**
     * находится только в стране или колонии
     * может быть несколко (можно увеличивать апгрейдом) (добавить)
     * может быть ноль, если не куплен начальный апгрейд вообще
     * в дефолтных чанках собирается налог на загрязнение природы
     */
    INDUSTRIAL,
    /**
    может находится вне страны
    самостоятельная зона, может быть на спавне
     */
    SHOP,
    /**
    находится только в стране или колонии

    АТМ можно ставить где угодно, но в зоне банка не будет комиссии
     */
    BANK,
    /**
    находится только в стране или колонии
     */
    HOSPITAL,
    /**
    находится только в стране или колонии
     */
    PARK,
    /**
    находится только в стране или колонии
     */
    CHURCH,
    /**
    находится только в стране или колонии
     */
    LIBRARY,
    /**
    находится только в стране или колонии
     */
    GREENHOUSE,
    /**
     * infra/military-diplomacy-design.md §3.1 — военный объект. Находится
     * только в стране или колонии, как и большинство типов выше. Скрыт от
     * посторонних на карте/в GET /zones (право viewMilitary, см. §3.2) —
     * скрытость реализована на бэкенде сайта, не здесь; для плагина это
     * обычный тип зоны, как и остальные.
     */
    MILITARY,
}
/*
для всех:
    В апдейт углов зоны сделать кулдаун 2 дня (зоны страны и колоний)
 */